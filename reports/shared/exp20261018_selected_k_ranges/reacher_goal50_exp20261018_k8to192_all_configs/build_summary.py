"""Build data/ summaries for the Reacher goal50 K8-192 all-configs sweep
on release hudm-mwm-exponential-k1to192-20261018.

Source: reports/research/reacher_goal50_exp20261018_k8to192_all_configs
(config configs/research/reacher_goal50_exp20261018_k8to192_all_configs.yaml, generated by
scripts/research/gen_exp20261018_all_configs.py; Slurm array 9145589).
Splits the cells into three files by run name:

- adaptive_summary.json: runs 02-26, the 19 adaptive schedules on the new
  dense checkpoint, floored to K>=8.
- singlek_summary.json: "*_single_k*" runs, the release's singleton
  checkpoints K=8..192, all fixed finest.
- dense_fixed_levels_summary.json: "*_dense_level*" runs, the new dense
  checkpoint held fixed at K=8..192, no scheduling.

Eval/planner settings and the CEM pop_size x n_iter grid come from the config.

Usage: python build_summary.py
"""
from __future__ import annotations

import itertools
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[4]
sys.path.insert(0, str(ROOT))

from mwm.benchmark.summary import eval_summary_row  # noqa: E402

HERE = Path(__file__).resolve().parent
NAME = "reacher_goal50_exp20261018_k8to192_all_configs"
CONFIG = ROOT / "configs" / "research" / f"{NAME}.yaml"
SOURCE_DIR = ROOT / "reports" / "research" / NAME


def group_of(run_name: str) -> str:
    if "_single_k" in run_name:
        return "singlek_summary.json"
    if "_dense_level" in run_name:
        return "dense_fixed_levels_summary.json"
    return "adaptive_summary.json"


def cells_per_run(cfg: dict) -> int:
    sweep, excludes = cfg["sweep"], cfg.get("sweep_exclude", [])
    keys = list(sweep)
    combos = [dict(zip(keys, values)) for values in itertools.product(*sweep.values())]
    return sum(not any(all(c.get(k) == v for k, v in ex.items()) for ex in excludes) for c in combos)


def load_rows() -> list[dict]:
    rows = []
    # summary.json is written last, so its presence marks a finished cell.
    for summary_path in sorted(SOURCE_DIR.glob("*/summary.json")):
        eval_path = summary_path.parent / "eval.json"
        rows.append(eval_summary_row(summary_path.parent.name, eval_path, json.loads(eval_path.read_text())))
    return rows


def main() -> None:
    cfg = yaml.safe_load(CONFIG.read_text())
    n_cells = cells_per_run(cfg)
    run_names = [r["name"] for r in cfg["runs"]]
    rows = load_rows()
    (HERE / "data").mkdir(exist_ok=True)
    for name in ("adaptive_summary.json", "singlek_summary.json", "dense_fixed_levels_summary.json"):
        names = {n for n in run_names if group_of(n) == name}
        group = [r for r in rows if r["base_name"] in names]
        out = {
            "source_output_dir": str(SOURCE_DIR.relative_to(ROOT)),
            "config": str(CONFIG.relative_to(ROOT)),
            "runs_completed": len(group),
            "runs_target": len(names) * n_cells,
            "runs": group,
        }
        (HERE / "data" / name).write_text(json.dumps(out, indent=2))
        print(f"{name}: {len(group)}/{len(names) * n_cells}")


if __name__ == "__main__":
    main()
