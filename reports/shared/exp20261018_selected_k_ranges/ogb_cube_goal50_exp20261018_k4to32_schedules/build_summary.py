"""Build data/ summaries for the OGB Cube goal50 K4-32 schedule sweep
on release hudm-mwm-exponential-k1to192-20261018.

Sources:

- reports/research/ogb_cube_goal50_exp20261018_k4to32_schedules
  (config configs/research/ogb_cube_goal50_exp20261018_k4to32_schedules.yaml, generated by
  scripts/research/gen_exp20261018_k4to16_configs.py; Slurm array 9325243, fills 9495424 and 9574377): the 13 adaptive
  schedules with every "finest" replaced by level index 5 (K=32), plus the K=4 single-K and
  dense fixed-level baselines (the source sweep has none below K=8).
- reports/research/ogb_cube_goal50_exp20261018_k8to192_all_configs: the K=8,16,32 single-K and
  dense fixed-level baselines (same dense checkpoint, same n100 manifest, same CEM
  pop_size x n_iter grid).

Splits the cells into three files by run name:

- adaptive_summary.json: the 13 adaptive schedules.
- singlek_summary.json: "*_single_k*" runs, K=4,8,16,32.
- dense_fixed_levels_summary.json: "*_dense_level*" runs, K=4,8,16,32.

Usage: python build_summary.py
"""
from __future__ import annotations

import itertools
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[4]
sys.path.insert(0, str(ROOT))

from mwm.benchmark.summary import eval_summary_row  # noqa: E402

HERE = Path(__file__).resolve().parent
NAME = "ogb_cube_goal50_exp20261018_k4to32_schedules"
BASELINE_NAME = "ogb_cube_goal50_exp20261018_k8to192_all_configs"
BASELINE_K = (4, 8, 16, 32)
FILES = ("adaptive_summary.json", "singlek_summary.json", "dense_fixed_levels_summary.json")


def group_of(run_name: str) -> str | None:
    if "_single_k" in run_name:
        group = "singlek_summary.json"
    elif "_dense_level" in run_name:
        group = "dense_fixed_levels_summary.json"
    else:
        return "adaptive_summary.json"
    k = int(run_name.split("_k")[-1].split("_")[0])
    return group if k in BASELINE_K else None


def cells_per_run(cfg: dict) -> int:
    sweep, excludes = cfg["sweep"], cfg.get("sweep_exclude", [])
    keys = list(sweep)
    combos = [dict(zip(keys, values)) for values in itertools.product(*sweep.values())]
    return sum(not any(all(c.get(k) == v for k, v in ex.items()) for ex in excludes) for c in combos)


def load_rows(source_dir: Path) -> list[dict]:
    rows = []
    # summary.json is written last, so its presence marks a finished cell.
    for summary_path in sorted(source_dir.glob("*/summary.json")):
        eval_path = summary_path.parent / "eval.json"
        rows.append(eval_summary_row(summary_path.parent.name, eval_path, json.loads(eval_path.read_text())))
    return rows


def main() -> None:
    (HERE / "data").mkdir(exist_ok=True)
    groups = {name: {"sources": [], "configs": [], "runs": [], "target": 0} for name in FILES}
    # The schedule sweep owns the adaptive runs and K=4; the source sweep supplies K=8,16,32.
    for name, include_adaptive in ((NAME, True), (BASELINE_NAME, False)):
        config = ROOT / "configs" / "research" / f"{name}.yaml"
        source_dir = ROOT / "reports" / "research" / name
        cfg = yaml.safe_load(config.read_text())
        n_cells = cells_per_run(cfg)
        rows = load_rows(source_dir)
        for file_name, group in groups.items():
            if file_name == "adaptive_summary.json" and not include_adaptive:
                continue
            names = {r["name"] for r in cfg["runs"] if group_of(r["name"]) == file_name}
            if not names:
                continue
            group["sources"].append(str(source_dir.relative_to(ROOT)))
            group["configs"].append(str(config.relative_to(ROOT)))
            group["runs"] += [r for r in rows if r["base_name"] in names]
            group["target"] += len(names) * n_cells
    for file_name, group in groups.items():
        out = {
            "source_output_dir": group["sources"],
            "config": group["configs"],
            "runs_completed": len(group["runs"]),
            "runs_target": group["target"],
            "runs": group["runs"],
        }
        (HERE / "data" / file_name).write_text(json.dumps(out, indent=2))
        print(f"{file_name}: {len(group['runs'])}/{group['target']}")


if __name__ == "__main__":
    main()
