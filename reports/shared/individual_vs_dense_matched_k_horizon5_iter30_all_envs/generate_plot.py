"""Regenerate plot.png from the data/ in this folder.

Individually-trained-K vs. dense-matched-K success rate, all four
environments (TwoRoom, OGB Cube, Reacher, PushT), on the exponential
K=[1,2,4,8,16,32,64,128,192] grid -- for BOTH goal_offset=25 (solid lines,
filled markers) and goal_offset=50 (dashed lines, hollow markers), overlaid
on the same 4 panels. Fixed eval protocol: horizon=5, receding_horizon=5,
pop_size=300, elite_frac=0.1 (30 elites), n_iter=30, 100 episodes, seed 42.

Every point comes from the GitHub release hudm-mwm-exponential-k1to192-20261018:
- "Individually-trained": the release's nine singleton checkpoints
  (<env>_single_k<K>.pt), exported to
  checkpoints_mwm/hudm_exp20261018_{env}_single_kXXX.
- "Dense (matched K)": the release's one K=[1,2,4,...,192] dense checkpoint
  (<env>_dense.pt), exported to checkpoints_mwm/hudm_exp20261018_{env}_dense,
  held fixed at level K for MPC/CEM/rollout, no scheduling.

Run definitions: configs/research/{env}_goal{25,50}_exp20261018_{dense,single}_k1to192_horizon5_iter30.yaml
(generated by scripts/research/gen_exp20261018_individual_vs_dense_configs.py).
The previous release's (std20261008, K=48..192) inputs are kept in data/.

Color always encodes series type (individual / dense); linestyle +
filled-vs-hollow markers always encode goal_offset (solid+filled = 25,
dashed+hollow = 50).

Usage: python generate_plot.py  (writes plot.png in this directory)
"""
from __future__ import annotations

import json
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

HERE = Path(__file__).resolve().parent

ORANGE = "#eb6834"
BLUE = "#2a78d6"
GRID = "#d9d9d6"

TAG = "exp20261018"
RELEASE = "hudm-mwm-exponential-k1to192-20261018"
ALL_LEVELS = [1, 2, 4, 8, 16, 32, 64, 128, 192]

ENVS = [
    ("tworoom", "TwoRoom"),
    ("ogb_cube", "OGB Cube"),
    ("reacher", "Reacher"),
    ("pusht", "PushT"),
]

GOALS = [
    (25, "-", True),   # (goal_offset, linestyle, filled)
    (50, "--", False),
]


def load_success_by_k(env: str, goal: int) -> tuple[dict[int, float], dict[int, float]]:
    """(individually-trained, dense-matched) success rate by K for one env/goal."""
    out = []
    for family in ("single", "dense"):
        data = json.load(open(HERE / "data" / f"{env}_goal{goal}_{TAG}_{family}_summary.json"))
        out.append({int(r["name"].removeprefix(f"{family}_k")): r["success_rate"] for r in data["runs"]})
    return out[0], out[1]


def main() -> None:
    fig, axes = plt.subplots(4, 1, figsize=(7.5, 12), dpi=150, sharex=True)
    fig.patch.set_facecolor("#fcfcfb")

    for ax, (env, label) in zip(axes, ENVS):
        ax.set_facecolor("#fcfcfb")

        for goal, ls, filled in GOALS:
            individual, dense = load_success_by_k(env, goal)

            mfc_o = ORANGE if filled else "white"
            mfc_b = BLUE if filled else "white"

            ax.plot(ALL_LEVELS, [individual[k] for k in ALL_LEVELS], color=ORANGE, marker="o",
                     lw=2, ms=6, ls=ls, markerfacecolor=mfc_o,
                     label=f"Individually-trained K (goal={goal})")
            ax.plot(ALL_LEVELS, [dense[k] for k in ALL_LEVELS], color=BLUE, marker="s",
                     lw=2, ms=6, ls=ls, markerfacecolor=mfc_b,
                     label=f"Dense (matched K, goal={goal})")

        ax.set_ylim(-5, 105)
        ax.set_ylabel("Success rate (%)", fontsize=10)
        ax.set_title(label, fontsize=12, fontweight="bold", loc="left")
        ax.grid(True, color=GRID, lw=0.8)
        for spine in ax.spines.values():
            spine.set_color(GRID)

    handles, labels = axes[0].get_legend_handles_labels()
    fig.legend(handles, labels, loc="lower center", fontsize=9, framealpha=0.95,
               ncol=2, bbox_to_anchor=(0.5, -0.01))
    axes[-1].set_xlabel("K (fidelity level)", fontsize=11)
    axes[-1].set_xscale("log", base=2)
    axes[-1].set_xticks(ALL_LEVELS, [str(k) for k in ALL_LEVELS])
    axes[-1].minorticks_off()

    fig.suptitle(
        "Individually-trained K vs. dense-matched K (no scheduling)\n"
        "goal=25 (solid/filled) vs. goal=50 (dashed/hollow)\n"
        f"release {RELEASE}, 100 episodes, horizon=5, pop=300/elite=30/iter=30",
        fontsize=11.5, fontweight="bold", y=0.998,
    )
    fig.tight_layout(rect=(0, 0.06, 1, 0.96))

    out = HERE / "plot.png"
    fig.savefig(out, bbox_inches="tight")
    print(f"saved {out}")


if __name__ == "__main__":
    main()
