"""Build data/ summaries for the Reacher goal25 K16-64 schedule sweep
on release hudm-mwm-exponential-k1to192-20261018.

Sources:

- adaptive_summary.json: the 13 adaptive schedules from
  reports/research/reacher_goal25_exp20261018_k16to64_schedules
  (config configs/research/reacher_goal25_exp20261018_k16to64_schedules.yaml, generated by
  scripts/research/gen_exp20261018_k4to16_configs.py; Slurm array 9735114), every "finest"
  replaced by level index 6 (K=64); coarse floor raised to K=16.
- singlek_summary.json / dense_fixed_levels_summary.json: the K=16,32,64 baselines reused
  from reports/research/reacher_goal25_exp20261018_k8to192_all_configs (same dense
  checkpoint, same n100 manifest, same CEM pop_size x n_iter grid), i.e. the release's
  singleton checkpoints and the dense checkpoint held fixed at one level.

Usage: python build_summary.py
"""
from __future__ import annotations

import itertools
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[4]
sys.path.insert(0, str(ROOT))

from mwm.benchmark.summary import eval_summary_row  # noqa: E402

HERE = Path(__file__).resolve().parent
NAME = "reacher_goal25_exp20261018_k16to64_schedules"
BASELINE_NAME = "reacher_goal25_exp20261018_k8to192_all_configs"
BASELINE_K = (16, 32, 64)


def cells_per_run(cfg: dict) -> int:
    sweep, excludes = cfg["sweep"], cfg.get("sweep_exclude", [])
    keys = list(sweep)
    combos = [dict(zip(keys, values)) for values in itertools.product(*sweep.values())]
    return sum(not any(all(c.get(k) == v for k, v in ex.items()) for ex in excludes) for c in combos)


def load_rows(source_dir: Path) -> list[dict]:
    rows = []
    # summary.json is written last, so its presence marks a finished cell.
    for summary_path in sorted(source_dir.glob("*/summary.json")):
        eval_path = summary_path.parent / "eval.json"
        rows.append(eval_summary_row(summary_path.parent.name, eval_path, json.loads(eval_path.read_text())))
    return rows


def baseline_group(run_name: str) -> str | None:
    if "_single_k" in run_name:
        group = "singlek_summary.json"
    elif "_dense_level" in run_name:
        group = "dense_fixed_levels_summary.json"
    else:
        return None
    k = int(run_name.split("_k")[-1].split("_")[0])
    return group if k in BASELINE_K else None


def write(name: str, config: Path, source_dir: Path, names: set[str], rows: list[dict], n_cells: int) -> None:
    group = [r for r in rows if r["base_name"] in names]
    out = {
        "source_output_dir": str(source_dir.relative_to(ROOT)),
        "config": str(config.relative_to(ROOT)),
        "runs_completed": len(group),
        "runs_target": len(names) * n_cells,
        "runs": group,
    }
    (HERE / "data" / name).write_text(json.dumps(out, indent=2))
    print(f"{name}: {len(group)}/{len(names) * n_cells}")


def main() -> None:
    (HERE / "data").mkdir(exist_ok=True)

    config = ROOT / "configs" / "research" / f"{NAME}.yaml"
    source_dir = ROOT / "reports" / "research" / NAME
    cfg = yaml.safe_load(config.read_text())
    names = {r["name"] for r in cfg["runs"]}
    write("adaptive_summary.json", config, source_dir, names, load_rows(source_dir), cells_per_run(cfg))

    config = ROOT / "configs" / "research" / f"{BASELINE_NAME}.yaml"
    source_dir = ROOT / "reports" / "research" / BASELINE_NAME
    cfg = yaml.safe_load(config.read_text())
    rows = load_rows(source_dir)
    for name in ("singlek_summary.json", "dense_fixed_levels_summary.json"):
        names = {r["name"] for r in cfg["runs"] if baseline_group(r["name"]) == name}
        write(name, config, source_dir, names, rows, cells_per_run(cfg))


if __name__ == "__main__":
    main()
